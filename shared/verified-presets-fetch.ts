import { defaultChaos, defaultPagination, type FieldSpec, type MockAuth, type MockOperation, type MockSpec } from "./mock-spec";

const checkedAt = "2026-11-10";

function field(name: string, kind: FieldSpec["kind"], extra: Partial<FieldSpec> = {}): FieldSpec {
  return { name, kind, ...extra };
}

function object(name: string, children: FieldSpec[]): FieldSpec {
  return { name, kind: "object", children };
}

function op(
  partial: Omit<MockOperation, "headers" | "pagination" | "contentType"> & {
    pagination?: Partial<MockOperation["pagination"]>;
    contentType?: string;
  },
): MockOperation {
  const { pagination, contentType, ...rest } = partial;
  return {
    ...rest,
    headers: {},
    contentType: contentType ?? "application/json; charset=utf-8",
    pagination: { ...defaultPagination(), ...pagination },
  };
}

function preset(input: {
  id: string;
  name: string;
  pack: string;
  vendor: string;
  summary: string;
  docUrl: string;
  sourceUrl: string;
  differences: string[];
  operations: MockOperation[];
  auth?: MockAuth;
}): {
  id: string;
  name: string;
  pack: string;
  vendor: string;
  fidelity: "verified";
  curated: true;
  summary: string;
  notes: string[];
  attribution: string;
  sourceUrl: string;
  spec: MockSpec;
} {
  return {
    id: input.id,
    name: input.name,
    pack: input.pack,
    vendor: input.vendor,
    fidelity: "verified",
    curated: true,
    summary: input.summary,
    notes: input.differences,
    attribution: "Checked against a public vendor reference or, when that page is blocked, the integration test fixture plus the public client. See /presets/ATTRIBUTION.md.",
    sourceUrl: input.sourceUrl,
    spec: {
      version: 1,
      source: {
        kind: "preset",
        id: input.id,
        name: input.name,
        fidelity: "verified",
        attribution: "Public API reference or demisto/content test fixture (MIT).",
        sourceUrl: input.docUrl,
        notes: input.differences,
        verification: {
          status: "verified",
          docUrl: input.docUrl,
          checkedAt,
          differences: input.differences,
        },
      },
      operations: input.operations,
      chaos: defaultChaos(input.id),
      totalRecords: 200,
      auth: input.auth ?? { mode: "none" },
    },
  };
}

