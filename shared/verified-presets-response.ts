import { defaultChaos, defaultPagination, type FieldSpec, type MockAuth, type MockOperation, type MockSpec } from "./mock-spec";

const checkedAt = "2026-11-10";

function field(name: string, kind: FieldSpec["kind"], extra: Partial<FieldSpec> = {}): FieldSpec {
  return { name, kind, ...extra };
}

function object(name: string, children: FieldSpec[]): FieldSpec {
  return { name, kind: "object", children };
}

function op(
  partial: Omit<MockOperation, "headers" | "pagination" | "contentType"> & {
    pagination?: Partial<MockOperation["pagination"]>;
    contentType?: string;
  },
): MockOperation {
  const { pagination, contentType, ...rest } = partial;
  return {
    ...rest,
    headers: {},
    contentType: contentType ?? "application/json; charset=utf-8",
    pagination: { ...defaultPagination(), style: "none", ...pagination },
  };
}

function preset(input: {
  id: string;
  name: string;
  pack: string;
  vendor: string;
  summary: string;
  docUrl: string;
  sourceUrl: string;
  differences: string[];
  operations: MockOperation[];
  auth?: MockAuth;
}): {
  id: string;
  name: string;
  pack: string;
  vendor: string;
  fidelity: "verified";
  curated: true;
  summary: string;
  notes: string[];
  attribution: string;
  sourceUrl: string;
  spec: MockSpec;
} {
  return {
    id: input.id,
    name: input.name,
    pack: input.pack,
    vendor: input.vendor,
    fidelity: "verified",
    curated: true,
    summary: input.summary,
    notes: input.differences,
    attribution: "Checked against a public vendor reference or, when that page is blocked, the integration test fixture plus the public client. See /presets/ATTRIBUTION.md.",
    sourceUrl: input.sourceUrl,
    spec: {
      version: 1,
      source: {
        kind: "preset",
        id: input.id,
        name: input.name,
        fidelity: "verified",
        attribution: "Public API reference or demisto/content client (MIT).",
        sourceUrl: input.docUrl,
        notes: input.differences,
        verification: { status: "verified", docUrl: input.docUrl, checkedAt, differences: input.differences },
      },
      operations: input.operations,
      chaos: defaultChaos(input.id),
      totalRecords: 40,
      auth: input.auth ?? { mode: "none" },
    },
  };
}

const bearer: MockAuth = { mode: "bearer", bearer: { token: "dummy-bearer" } };

function key(name: string, value = "dummy-key"): MockAuth {
  return { mode: "api-key", apiKey: { in: "header", name, value } };
}

function ids(id: string, method: string, path: string, summary: string, header?: Record<string, string>): MockOperation {
  return op({
    id,
    method,
    pathTemplate: path,
    summary,
    status: 200,
    list: true,
    envelope: { type: "wrapped", arrayKey: "resources" },
    headerMatch: header,
    pagination: { style: "offset", limitParam: "limit", offsetParam: "offset" },
    record: field("resource", "id"),
  });
}

