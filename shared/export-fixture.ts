import { generateMockResponse } from "./generate";
import type { MockSpec } from "./mock-spec";
const FIXTURE_BODY_MAX = 8_000;

export interface FixtureFile {
  pytest: string;
  testData: string;
}

const PYTEST = `"""Offline requests_mock fixtures generated by PAN Parrot.

The live catch URL is in test_data.json. These tests do not call it.
Dummy mock credentials are not included.
"""
import json
from pathlib import Path

import pytest
import requests
import requests_mock

DATA = json.loads(Path(__file__).with_name("test_data.json").read_text())


@pytest.mark.parametrize("operation", DATA["operations"], ids=lambda operation: operation["id"])
def test_operation_fixture(operation):
    url = DATA["baseUrl"].rstrip("/") + operation["path"]
    kwargs = {"status_code": operation["status"]}
    body = operation["body"]
    if isinstance(body, (dict, list)):
        kwargs["json"] = body
    else:
        kwargs["text"] = "" if body is None else str(body)
    with requests_mock.Mocker() as mock:
        mock.register_uri(operation["method"], url, **kwargs)
        response = requests.request(operation["method"], url)
    assert response.status_code == operation["status"]
    if isinstance(body, (dict, list)):
        assert response.json() == body
    elif body is not None:
        assert response.text == str(body)
`;

export function exportFixture(spec: MockSpec, baseUrl: string): FixtureFile {
  const quiet = { ...spec, chaos: { ...spec.chaos, enabled: false } };
  const operations = spec.operations.slice(0, 40).map((operation) => {
    const query = { limit: "2", ...(operation.queryMatch || {}) };
    const generated = generateMockResponse({
      spec: quiet,
      operation,
      query,
      pathParams: {},
      requestIndex: 1,
      requestUrl: baseUrl,
    });
    const path = concretePath(operation.pathTemplate, query);
    return {
      id: operation.id,
      method: operation.method === "ANY" ? "GET" : operation.method,
      path,
      status: generated.status,
      body: fixtureBody(generated.body),
    };
  });
  return {
    pytest: PYTEST,
    testData: JSON.stringify(
      {
        name: spec.source.name,
        baseUrl,
        note: "Generated samples. Secrets from the mock's dummy auth are not included.",
        operations,
      },
      null,
      2,
    ),
  };
}

function concretePath(template: string, query: Record<string, string>): string {
  const path = template.replace(/\{[^}]+\}/g, "example");
  const params = new URLSearchParams();
  for (const [key, value] of Object.entries(query)) {
    if (key === "limit") continue;
    params.set(key, value);
  }
  const suffix = params.toString();
  return suffix ? `${path}?${suffix}` : path;
}

function fixtureBody(body: string): unknown {
  const text = body.length > FIXTURE_BODY_MAX ? body.slice(0, FIXTURE_BODY_MAX) : body;
  const trimmed = text.trim();
  if (trimmed.startsWith("{") || trimmed.startsWith("[")) {
    try {
      return JSON.parse(text) as unknown;
    } catch {
      return text;
    }
  }
  return text;
}
